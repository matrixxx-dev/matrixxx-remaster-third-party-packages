#!/bin/bash

## ########################################################################## ##
## Delete working data directory
##
## ########################################################################## ##
## includes:
source ./part2.ini

## declaration
CALLED="$1"

## -------------------------------------------------------------------------- ##
## MAIN:
## -------------------------------------------------------------------------- ##
DIR_LIST="${TEMP_COLLECTION_DIR} ${TEMP_COLLECTION_DIR}-64"

for dir in ${DIR_LIST}
do
  echo "remove directory: ${dir}"
  sudo rm -rf "${dir}"
done

## -------------------------------------------------------------------------- ##
## pause:
[ "${CALLED}" = "called" ] || { echo "Press enter to continue..."; read -r; }

## ########################################################################## ##
exit 0
